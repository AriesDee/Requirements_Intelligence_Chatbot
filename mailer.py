"""
mailer.py — Email sender for UKG Tools

Sends the downloaded report as an email attachment using the Safeway internal
mail relay (no authentication required).

SMTP config (add to input/config.json):
  smtp_from:    aries.domingo@albertsons.com
  smtp_to:      ["aries.domingo@albertsons.com"]
  smtp_subject: UKG Audit Report - Integration Daily Extract
  smtp_host:    mailrouter.safeway.com   (optional — this is the default)
  smtp_port:    25                       (optional — this is the default)
"""

import sys
import smtplib
import logging
import json
from email.message import EmailMessage
from email.utils import formatdate
from pathlib import Path

logger = logging.getLogger('ukg_api_tool.mailer')

SMTP_HOST_DEFAULT = 'mailrouter.safeway.com'
SMTP_PORT_DEFAULT = 25

_MIME = {
    '.xlsx': 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet',
    '.xls':  'application/vnd.ms-excel',
    '.pdf':  'application/pdf',
    '.csv':  'text/csv',
    '.json': 'application/json',
    '.txt':  'text/plain',
}


def _load_config() -> dict:
    _base = Path(sys.executable).parent if getattr(sys, 'frozen', False) else Path(__file__).parent
    config_file = _base / 'input' / 'config.json'
    if config_file.exists():
        with open(config_file, encoding='utf-8') as f:
            return json.load(f)
    return {}


def send(attachment: Path, subject: str | None = None, body: str | None = None,
         to: list[str] | None = None, is_test: bool = False):
    """
    Send `attachment` as an email via the Safeway internal mail relay.

    Parameters
    ----------
    attachment : Path   — file to attach
    subject    : str    — email subject (defaults to smtp_subject in config.json, then filename)
    body       : str    — plain-text body (defaults to a short note)
    to         : list   — recipient list (overrides smtp_to in config.json)
    is_test    : bool   — prepends '[Test Email]' to the subject when True
    """
    config    = _load_config()
    smtp_host = config.get('smtp_host', SMTP_HOST_DEFAULT)
    smtp_port = int(config.get('smtp_port', SMTP_PORT_DEFAULT))
    from_addr = config.get('smtp_from', '')

    if to:
        to_addrs = to
    else:
        raw_to = config.get('smtp_to', [])
        if isinstance(raw_to, str):
            to_addrs = [a.strip() for a in raw_to.split(',') if a.strip()]
        else:
            to_addrs = [a.strip() for a in raw_to if a.strip()]

    if not from_addr:
        raise ValueError('smtp_from is not set in input/config.json.')
    if not to_addrs:
        raise ValueError('smtp_to is not set in input/config.json.')
    if not attachment.exists():
        raise FileNotFoundError(f'Attachment not found: {attachment}')

    base_subject  = subject or config.get('smtp_subject') or f'UKG Report: {attachment.name}'
    final_subject = f'[Test Email] {base_subject}' if is_test else base_subject

    body = body or (
        f'Please find the attached UKG report: {attachment.name}\n\n'
        f'Generated by audit_report_tool.py'
    )

    msg = EmailMessage()
    msg['Subject'] = final_subject
    msg['From']    = from_addr
    msg['To']      = ', '.join(to_addrs)
    msg['Date']    = formatdate(localtime=True)
    msg.set_content(body)

    mime_type = _MIME.get(attachment.suffix.lower(), 'application/octet-stream')
    main_type, sub_type = mime_type.split('/', 1)
    msg.add_attachment(
        attachment.read_bytes(),
        maintype=main_type,
        subtype=sub_type,
        filename=attachment.name,
    )

    logger.info(f'Sending email "{final_subject}" → {to_addrs} via {smtp_host}:{smtp_port}')

    with smtplib.SMTP(smtp_host, smtp_port) as smtp:
        smtp.send_message(msg)

    logger.info('Email sent successfully')
    print(f'Email sent:    {", ".join(to_addrs)}')
    print(f'Subject:       {final_subject}')
